# When we want to create a variable, we make up a word,
# use the equal sign and then assign it a data type.
# whenever the computer sees our variable word it will
# always use the data inside.

# Variable Naming Rules
# 1. A variable MUST start with letter and cannot start with a number
# 2. A variable can be a mixed of letters and numbers BUT not symbols
# 3. A variable CANNOT be a Python keyword
# 4. variables with multiple words do not have spaces










# Variable Naming Conventions
# we use naming conventions because we CANNOT have spaces in 
# variable names

AppleNum = 100
